#!/usr/bin/env python3
# Generate src/app/ToolbarIcons.h from the SVG icon strings in ../ts/Toolbar.ts,
# so the native toolbar uses exactly the same icons as the web version.
import os, re
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "..", "..", "ts", "Toolbar.ts")).read()
icons = []
for m in re.finditer(r'readonly (\w*Icon\w*)\s*=\s*((?:"[^"]*"\s*\+?\s*)+);', src):
    name = m.group(1)
    parts = re.findall(r'"([^"]*)"', m.group(2))
    icons.append((name, "".join(parts)))
out = ["// GENERATED by tools/extract_icons.py from ../ts/Toolbar.ts -- do not edit", "",
       "#pragma once", "", "namespace ToolbarIcons {"]
for name, svg in icons:
    out.append('inline const char *%s = R"SVG(%s)SVG";' % (name, svg))
out.append("}")
open(os.path.join(here, "..", "src", "app", "ToolbarIcons.h"), "w").write("\n".join(out) + "\n")
print(len(icons), "icons")
